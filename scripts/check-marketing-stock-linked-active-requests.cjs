const fs = require('node:fs');
const assert = require('node:assert/strict');
const ts = require('typescript');
const source = fs.readFileSync('src/marketing/linkedStockRequests.ts', 'utf8');
const transpiled = ts.transpileModule(source, { fileName: 'linkedStockRequests.ts', compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } });
const exportsObj = {};
new Function('exports', 'require', transpiled.outputText)(exportsObj, require);
const { collectLinkedActiveRequests, searchLinkedActiveRequests } = exportsObj;
const linked = (id, no, kind, created) => ({ requestId: id, requestNo: no, requestKind: kind, status: 'created', requestedAt: created, requestedByName: 'موظف العمليات', sourceLocationName: 'المستودع', destinationLocationName: 'الصالة' });
const car = (id, vin, reqs) => ({ id, vin, car_name: 'اكسنت', location_name: 'المستودع', active_request_details: reqs });
const a=linked('tr-id','TR-20261012-000263','transfer','2026-10-12T12:00:00Z');
const b=linked('ph-id','PH-20261012-000266','photography','2026-10-12T13:00:00Z');
const cars = [car('v1','734431',[a,a]),car('v2','128258',[a]),car('v3','778899',[b]),car('v4','111222',[])];
const results = collectLinkedActiveRequests(cars);
assert.equal(results.length,2,'one request per transfer, not one per vehicle');
assert.equal(results[0].requestNo,b.requestNo,'newest first');
const transfer = results.find(r=>r.requestNo===a.requestNo);
assert.equal(transfer.cars.length,2,'no duplicate VIN when a request appears twice');
assert.deepEqual(transfer.cars.map(x=>x.vin),['734431','128258']);
assert.equal(searchLinkedActiveRequests(results,'734431')[0].requestNo,a.requestNo);
assert.equal(searchLinkedActiveRequests(results,'TR-20261012')[0].requestNo,a.requestNo);
assert.equal(searchLinkedActiveRequests(results,'موظف العمليات').length,2);
assert.equal(searchLinkedActiveRequests(results,'notfound').length,0);
assert.equal(searchLinkedActiveRequests(results,'').length,2);
const page=fs.readFileSync('src/marketing/pages/StockPage.tsx','utf8');
const server=fs.readFileSync('server/marketing/index.ts','utf8');
assert.ok(page.includes('الطلبات المرتبطة بالسيارات') && page.includes('عرض الطلبات المرتبطة'));
assert.ok(page.includes('setRequestTab("linked")') && page.includes('setPageTab("requests")'));
assert.ok(page.includes('لا توجد طلبات تصوير نشطة في هذه القائمة'));
assert.ok(server.includes("'requestId',r.id::text") && server.includes("'requestedByName',r.requested_by_name"));
assert.ok(server.includes("where rv.vehicle_id=v.id and r.is_deleted=false and r.cancelled_at is null and r.status<>'completed'"));
assert.ok(server.includes("where r.request_kind='photography' and r.is_deleted=false"));
assert.ok(page.includes('request.requestKind === "transfer" ? "طلب نقل" : "طلب تصوير"'));
assert.ok(page.includes('selectedLinkedRequest') && page.includes('/operations/transfers'));
